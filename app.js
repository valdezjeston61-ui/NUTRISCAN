class Util {
  static $(id) { return document.getElementById(id); }
  static esc(s) {
    return String(s).replace(/[&<>"']/g, c => ({
      '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
    }[c]));
  }
  static fmt(n) {
    const r = Math.abs(n) >= 10 ? Math.round(n) : Math.round(n * 10) / 10;
    return String(r);
  }
  static clamp(v, lo, hi) { return Math.max(lo, Math.min(hi, v)); }
  static randomFrom(arr) { return arr[Math.floor(Math.random() * arr.length)]; }
}
