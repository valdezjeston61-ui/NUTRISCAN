/* ===========================================================
   FOOD MODEL
=========================================================== */
class FoodItem {
  constructor(o = {}) {
    const num = v => (typeof v === 'number' && isFinite(v)) ? v : 0;
    this.name = String(o.name || o.food || 'Unidentified meal');
    this.category = String(o.category || 'Food');
    this.calories = num(o.calories ?? o.kcal);
    this.protein = num(o.protein);
    this.carbs = num(o.carbs);
    this.fat = num(o.fat);
    this.fiber = num(o.fiber);
    this.sugar = num(o.sugar);
    this.sodium = num(o.sodium);
    this.grade = String(o.grade || 'C');
    this.score = clamp(Math.round(num(o.score)) || 60, 0, 100);
    this.emoji = String(o.emoji || '🍽️');
    this.description = String(o.description || 'A food profile generated by NutriScan.');
    this.insight = String(o.insight || '');
    this.vegetarian = typeof o.vegetarian === 'boolean' ? o.vegetarian : null;
    this.allergens = Array.isArray(o.allergens)
      ? o.allergens.map(a => String(a).toLowerCase())
      : [];
    this.ingredients = Array.isArray(o.ingredients) ? o.ingredients.map(String) : [];
    this.benefits = Array.isArray(o.benefits) ? o.benefits.map(String) : [];
    this.risks = Array.isArray(o.risks) ? o.risks.map(String) : [];
    this.alternatives = (Array.isArray(o.alternatives) ? o.alternatives : [])
      .slice(0, 3)
      .map(a => Array.isArray(a) ? [String(a[0] || '🥗'), String(a[1] || ''), String(a[2] || '')] : null)
      .filter(Boolean);
    this.scannedAt = new Date();
  }
  static toneOf(grade) {
    return /^(A|B\+)/.test(grade) ? 'tone-good' : grade === 'B' ? 'tone-mid' : 'tone-bad';
  }
  static gradeFromScore(s) {
    return s >= 95 ? 'A+' : s >= 88 ? 'A' : s >= 80 ? 'B+' : s >= 70 ? 'B' : s >= 50 ? 'C' : 'D';
  }
  get tone() { return FoodItem.toneOf(this.grade); }
  amount(key, grams) { return this[key] * grams / 100; }
}

/* ===========================================================
   SCAN HISTORY
=========================================================== */
class ScanHistory {
  constructor() {
    this.storageKey = 'nutriscan_history';
    this.items = this.load();
  }
  load() {
    try {
      const saved = JSON.parse(localStorage.getItem(this.storageKey) || '[]');
      return saved.map(item => {
        const f = new FoodItem(item);
        f.scannedAt = new Date(item.scannedAt);
        return f;
      });
    } catch { return []; }
  }
  save() {
    try {
      localStorage.setItem(this.storageKey, JSON.stringify(this.items));
    } catch {
      showToast('Unable to save history on this device.');
    }
  }
  add(item) {
    this.items = [
      item,
      ...this.items.filter(i => i.name.toLowerCase() !== item.name.toLowerCase())
    ].slice(0, AppConfig.MAX_HISTORY);
    this.save();
  }
  clear() { this.items = []; this.save(); }
  getAll() { return [...this.items]; }
}

