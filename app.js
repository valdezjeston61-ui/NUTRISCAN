class NutriScanApp {
  constructor() {
    this.history = new ScanHistory();
    this.analyzer = new Analyzer();
    this.channel = new Channel();
    this.imageFile = null;
    this.imageUrl = null;
    this.stream = null;
    this.food = null;
    this.plate = [];
    this.$ = id => document.getElementById(id);

    this.bindEvents();
    this.setDate();
    this.renderHistory();
  }

  setDate() {
    this.$('today').textContent = new Intl.DateTimeFormat(undefined, {
      weekday: 'short', month: 'short', day: 'numeric'
    }).format(new Date());
  }

  bindEvents() {
    this.$('uploadBtn').addEventListener('click', () => this.$('fileInput').click());
    this.$('fileInput').addEventListener('change', e => {
      this.loadImage(e.target.files[0]);
      e.target.value = '';
    });
    this.$('cameraBtn').addEventListener('click', () => this.openCamera());
    this.$('closeCamera').addEventListener('click', () => this.closeCamera());
    this.$('captureBtn').addEventListener('click', () => this.capture());
    this.$('analyzeBtn').addEventListener('click', () => this.analyzeText());
    this.$('foodName').addEventListener('keydown', e => {
      if (e.key === 'Enter') {
        e.preventDefault();
        this.analyzeText();
      }
    });
    this.$('retryBtn').addEventListener('click', () => this.analyzePhoto());
    this.$('changePhotoBtn').addEventListener('click', () => this.$('fileInput').click());
    this.$('plateAdd').addEventListener('click', () => this.addPlateToHistory());
    this.$('clearHistory').addEventListener('click', () => {
      this.history.clear();
      this.renderHistory();
      showToast('Scan history cleared.');
    });
    this.$('cameraModal').addEventListener('click', e => {
      if (e.target === this.$('cameraModal')) this.closeCamera();
    });
    document.addEventListener('keydown', e => {
      if (e.key === 'Escape') this.closeCamera();
    });

    this.setupDragAndDrop();
    this.setupMobileNavigation();
    this.$('plateList').addEventListener('change', e => this.onPlateChange(e));
  }

  setupDragAndDrop() {
    const zone = this.$('dropzone');
    ['dragenter', 'dragover'].forEach(t => zone.addEventListener(t, e => {
      e.preventDefault();
      zone.classList.add('dragging');
    }));
    ['dragleave', 'drop'].forEach(t => zone.addEventListener(t, e => {
      e.preventDefault();
      zone.classList.remove('dragging');
    }));
    zone.addEventListener('drop', e => {
      const f = e.dataTransfer.files[0];
      if (f) this.loadImage(f);
    });
    zone.addEventListener('click', e => {
      if (e.target.closest('.action-row')) return;
      this.$('fileInput').click();
    });
  }

  setupMobileNavigation() {
    document.querySelectorAll('.tabs [data-target]').forEach(button => {
      button.addEventListener('click', () => {
        document.querySelectorAll('.tabs button').forEach(i => i.classList.remove('active'));
        button.classList.add('active');
        const t = button.dataset.target;
        if (t === 'home') window.scrollTo({ top: 0, behavior: 'smooth' });
        if (t === 'history') document.querySelector('.bottom-grid').scrollIntoView({ behavior: 'smooth' });
        if (t === 'report') document.querySelector('.result-panel').scrollIntoView({ behavior: 'smooth' });
      });
    });
    this.$('profileBtn').addEventListener('click', () => {
      showToast('Profile settings can be added in a future version.');
    });
  }

  async resizeImage(file, maxSide = 1280, quality = 0.85) {
    return new Promise((resolve, reject) => {
      const url = URL.createObjectURL(file);
      const img = new Image();
      img.onload = () => {
        URL.revokeObjectURL(url);
        const scale = Math.min(1, maxSide / Math.max(img.width, img.height));
        const c = document.createElement('canvas');
        c.width = Math.round(img.width * scale);
        c.height = Math.round(img.height * scale);
        c.getContext('2d').drawImage(img, 0, 0, c.width, c.height);
        c.toBlob(b => b ? resolve(b) : reject(new Error('Could not process image.')), 'image/jpeg', quality);
      };
      img.onerror = () => {
        URL.revokeObjectURL(url);
        reject(new Error('Could not read image file.'));
      };
      img.src = url;
    });
  }

  async loadImage(file) {
    if (!file) return;
    this.channel.hideError();
    if (!file.type.startsWith('image/')) {
      this.channel.showError('Please choose a valid image file.');
      return;
    }
    if (file.size > AppConfig.MAX_IMAGE_SIZE) {
      this.channel.showError('Image is larger than 5MB. Please choose a smaller photo.');
      return;
    }
    try {
      const resized = await this.resizeImage(file);
      this.imageFile = new File([resized], 'food.jpg', { type: 'image/jpeg' });
      if (this.imageUrl) URL.revokeObjectURL(this.imageUrl);
      this.imageUrl = URL.createObjectURL(this.imageFile);
      const preview = this.$('preview');
      preview.src = this.imageUrl;
      preview.hidden = false;
      this.$('dropzone').classList.add('has-image');
      this.$('uploadTitle').textContent = file.name;
      this.$('uploadText').textContent = 'Reading every food on the plate…';
      this.$('retryRow').hidden = true;
      this.resetResults();
      await this.analyzePhoto();
    } catch (err) {
      this.channel.showError(err.message || 'Could not process this image.');
    }
  }

  resetResults() {
    this.food = null;
    this.plate = [];
    this.$('plate').hidden = true;
    this.$('statusPill').textContent = UI.messages.ready;
    this.$('statusPill').classList.remove('warn');
  }

  async analyzePhoto() {
    if (!this.imageFile) {
      this.channel.showError('Please choose a photo first.');
      return;
    }
    this.$('retryRow').hidden = true;
    this.$('uploadText').textContent = 'Reading every food on the plate…';

    const items = await this.analyzer.analyzeImage(this.channel, this.imageFile);

    if (!items) {
      this.$('uploadText').textContent = 'Could not read this photo';
      this.$('statusPill').textContent = 'UNAVAILABLE';
      this.$('statusPill').classList.add('warn');
      this.$('retryRow').hidden = false;
      return;
    }

    this.$('uploadText').textContent = `Found ${items.length} food item${items.length > 1 ? 's' : ''}`;
    this.$('retryRow').hidden = true;

    this.food = null;
    this.plate = items.map(i => ({ food: i.food, grams: i.grams, on: true }));
    this.renderPlate();
    this.$('statusPill').textContent = items.length > 1 ? 'PLATE DETECTED' : 'PHOTO ANALYSIS';
    this.$('statusPill').classList.remove('warn');

    if (items.length) this.renderReport(items[0].food);
    items.forEach(i => this.addHistory(i.food));
  }

  renderPlate() {
    if (!this.plate.length) {
      this.$('plate').hidden = true;
      return;
    }
    this.$('plate').hidden = false;
    const list = this.$('plateList');
    list.innerHTML = this.plate.map((it, i) => `
      <li>
        <label><input type="checkbox" data-pc="${i}" ${it.on ? 'checked' : ''}> ${esc(it.food.name)}</label>
        <span><input class="gin" type="number" min="1" max="2000" step="1" data-pg="${i}" value="${it.grams}" aria-label="Grams of ${esc(it.food.name)}"> g</span>
        <b>${Math.round(it.food.amount('calories', it.grams))} kcal</b>
      </li>`).join('');

    const active = this.plate.filter(i => i.on);
    const t = active.reduce((a, i) => {
      const f = i.food;
      return {
        kcal: a.kcal + f.amount('calories', i.grams),
        p: a.p + f.amount('protein', i.grams),
        c: a.c + f.amount('carbs', i.grams),
        f: a.f + f.amount('fat', i.grams),
        scoreW: a.scoreW + f.score * f.amount('calories', i.grams),
        w: a.w + f.amount('calories', i.grams)
      };
    }, { kcal: 0, p: 0, c: 0, f: 0, scoreW: 0, w: 0 });

    this.$('plateKcal').textContent = Math.round(t.kcal).toLocaleString();
    this.$('plateMacros').textContent = `Protein ${fmt(t.p)} g, carbs ${fmt(t.c)} g, fat ${fmt(t.f)} g`;

    const score = t.w ? t.scoreW / t.w : (active[0] ? active[0].food.score : 0);
    const grade = FoodItem.gradeFromScore(score);
    const badge = this.$('plateGrade');
    badge.textContent = grade;
    badge.classList.remove('tone-good', 'tone-mid', 'tone-bad');
    badge.classList.add(FoodItem.toneOf(grade));
    this.$('plateAdd').disabled = active.length === 0;
  }

  onPlateChange(e) {
    const c = e.target.dataset.pc;
    const g = e.target.dataset.pg;
    if (c !== undefined) {
      this.plate[+c].on = e.target.checked;
      this.renderPlate();
    }
    if (g !== undefined) {
      const v = parseFloat(e.target.value);
      if (isFinite(v) && v > 0) this.plate[+g].grams = clamp(Math.round(v), 1, 2000);
      this.renderPlate();
    }
  }

  addPlateToHistory() {
    const active = this.plate.filter(i => i.on);
    if (!active.length) return;
    active.forEach(i => this.addHistory(i.food));
    showToast(`${active.length} food${active.length > 1 ? 's' : ''} added to recent scans.`);
    this.$('plateAdd').textContent = UI.messages.added;
    setTimeout(() => {
      this.$('plateAdd').textContent = UI.messages.addPlate;
    }, 1400);
  }

  async analyzeText() {
    const q = this.$('foodName').value.trim();
    if (!q) {
      showToast('Upload a photo to let the analyzer identify the food, or type a name here.');
      this.$('foodName').focus();
      return;
    }
    const food = await this.analyzer.analyzeName(this.channel, q);
    if (!food) return;
    this.plate = [];
    this.$('plate').hidden = true;
    this.renderReport(food);
    this.$('statusPill').textContent = 'NAME ANALYSIS';
    this.addHistory(food);
  }

  renderReport(item) {
    this.food = item;
    this.$('statusPill').classList.remove('warn');
    this.$('foodTitle').textContent = item.emoji + ' ' + item.name;
    this.$('foodDesc').textContent = item.description;

    const n = document.createElement('span');
    n.textContent = Math.round(item.calories);
    const u = document.createElement('small');
    u.textContent = ' kcal';
    this.$('calories').replaceChildren(n, u);

    this.$('score').textContent = item.score + '/100';
    this.$('protein').textContent = fmt(item.protein) + 'g';
    this.$('carbs').textContent = fmt(item.carbs) + 'g';
    this.$('fat').textContent = fmt(item.fat) + 'g';

    this.renderList('benefits', item.benefits.length ? item.benefits : ['No specific benefits listed.']);
    this.renderList('risks', item.risks.length ? item.risks : ['No specific risks listed.']);
    this.renderIngredients(item.ingredients.length ? item.ingredients : ['Not specified']);
    this.renderAlternatives(item.alternatives.length ? item.alternatives : FALLBACK_ALTERNATIVES);

    if (window.innerWidth <= 850) {
      document.querySelector('.result-panel')?.scrollIntoView({ behavior: 'smooth' });
    }
  }

  renderList(id, items) {
    const list = this.$(id);
    const frag = document.createDocumentFragment();
    items.forEach(v => {
      const li = document.createElement('li');
      li.textContent = v;
      frag.appendChild(li);
    });
    list.replaceChildren(frag);
  }

  renderIngredients(items) {
    const c = this.$('ingredients');
    const frag = document.createDocumentFragment();
    items.forEach(v => {
      const s = document.createElement('span');
      s.className = 'tag';
      s.textContent = v;
      frag.appendChild(s);
    });
    c.replaceChildren(frag);
  }

  renderAlternatives(items) {
    const c = this.$('alternatives');
    const frag = document.createDocumentFragment();
    items.forEach(a => {
      const card = document.createElement('div');
      card.className = 'alt';
      const icon = document.createElement('div');
      icon.className = 'alt-icon';
      icon.textContent = a[0];
      const content = document.createElement('div');
      const t = document.createElement('b');
      t.textContent = a[1];
      const d = document.createElement('span');
      d.textContent = a[2];
      content.append(t, d);
      card.append(icon, content);
      frag.appendChild(card);
    });
    c.replaceChildren(frag);
  }

  addHistory(item) {
    this.history.add(item);
    this.renderHistory();
  }

  renderHistory() {
    const c = this.$('historyList');
    const items = this.history.getAll();
    if (!items.length) {
      const e = document.createElement('div');
      e.className = 'empty';
      e.textContent = 'Your analyzed meals will appear here.';
      c.replaceChildren(e);
      return;
    }
    const frag = document.createDocumentFragment();
    items.forEach(item => {
      const row = document.createElement('div');
      row.className = 'history-item';
      const thumb = document.createElement('div');
      thumb.className = 'history-thumb';
      thumb.textContent = item.emoji;
      const meta = document.createElement('div');
      meta.className = 'history-meta';
      const name = document.createElement('b');
      name.textContent = item.name;
      const time = document.createElement('span');
      time.textContent = new Date(item.scannedAt).toLocaleTimeString([], {
        hour: '2-digit',
        minute: '2-digit'
      }) + ' · estimate';
      meta.append(name, time);
      const kcal = document.createElement('div');
      kcal.className = 'history-kcal';
      kcal.textContent = Math.round(item.calories) + ' kcal';
      row.append(thumb, meta, kcal);
      frag.appendChild(row);
    });
    c.replaceChildren(frag);
  }

  async openCamera() {
    if (!navigator.mediaDevices?.getUserMedia) {
      this.channel.showError('Camera is unavailable. Try Upload photo instead.');
      return;
    }
    try {
      this.stream = await navigator.mediaDevices.getUserMedia({
        video: { facingMode: { ideal: 'environment' } },
        audio: false
      });
      this.$('cameraVideo').srcObject = this.stream;
      this.$('cameraModal').classList.add('open');
      await this.$('cameraVideo').play();
    } catch (err) {
      console.error('Camera error:', err);
      this.channel.showError('Camera permission denied or camera unavailable.');
      this.closeCamera();
    }
  }

  closeCamera() {
    if (this.stream) this.stream.getTracks().forEach(t => t.stop());
    this.stream = null;
    this.$('cameraVideo').srcObject = null;
    this.$('cameraModal').classList.remove('open');
  }

  capture() {
    const video = this.$('cameraVideo');
    if (!video.videoWidth) {
      this.channel.showError('Camera is still starting. Try again.');
      return;
    }
    const canvas = document.createElement('canvas');
    canvas.width = video.videoWidth;
    canvas.height = video.videoHeight;
    canvas.getContext('2d').drawImage(video, 0, 0, canvas.width, canvas.height);
    canvas.toBlob(blob => {
      if (!blob) {
        this.channel.showError('Unable to capture photo.');
        return;
      }
      const file = new File([blob], 'camera-capture.jpg', { type: 'image/jpeg' });
      this.closeCamera();
      this.loadImage(file);
    }, 'image/jpeg', 0.92);
  }
}

// Global toast helper
function showToast(message) {
  const el = document.getElementById('toast');
  el.textContent = message;
  el.classList.add('show');
  clearTimeout(showToast.timer);
  showToast.timer = setTimeout(() => el.classList.remove('show'), 2800);
}

