/* ===========================================================
   ANALYZER — reads every food on the plate,
   repairs truncated JSON so partial replies still work.
=========================================================== */
class Analyzer {
  static FOOD_FIELDS =
    '"name":"specific common English food name, e.g. Grilled Salmon Fillet",' +
    '"category":"Fruit|Vegetable|Protein|Grain|Dairy|Nut|Dish|Snack|Beverage",' +
    '"calories":number,"protein":number,"carbs":number,"fat":number,"fiber":number,"sugar":number,' +
    '"sodium":number,"score":number,"grade":"A+|A|B+|B|C|D",' +
    '"emoji":"a single food emoji","description":"one short sentence",' +
    '"vegetarian":boolean,' +
    '"allergens":["fish","shellfish","peanuts","tree nuts","dairy","eggs","gluten","soy","sesame"],' +
    '"ingredients":["string"],"benefits":["string"],"risks":["string"],' +
    '"alternatives":[["emoji","name","short reason"]],' +
    '"insight":"one short sentence about health impact"';

  static FOOD_RULES =
    'Rules: all nutrient values are per 100g (sodium in mg). "score" is 0-100. ' +
    'Use the most specific common English name you can. ' +
    '"allergens" lists only allergens that apply, else []. ' +
    '"alternatives" lists up to 3 healthier swaps, or [] if grade is A+ or A. ' +
    'Keep "description" and "insight" under 12 words. Keep each "alternatives" note under 8 words. ';

  static imagePrompt() {
    return 'You are a nutrition analyzer. Look at the photo and identify EVERY distinct food item on the plate, ' +
      'one item per entry. Do not merge separate foods. Do not skip sides, sauces, or garnishes. ' +
      'List at most 6 items to stay within limits.\n\n' +
      'Reply with ONLY a single valid JSON object, no markdown, no code fences, no text before or after:\n' +
      '{"items":[{' + Analyzer.FOOD_FIELDS + ',"grams":number}]}\n' +
      Analyzer.FOOD_RULES +
      '"grams" is your estimate of the visible portion of that specific item in grams. ' +
      'If the image contains no food at all, reply with ONLY: {"error":"Could not identify food"}';
  }

  static textPrompt(hint) {
    return 'You are a nutrition analyzer. Identify the food item. The user typed: "' + hint + '".\n\n' +
      'Reply with ONLY a single valid JSON object, no markdown, no code fences, no text before or after:\n{' +
      Analyzer.FOOD_FIELDS + '}\n' + Analyzer.FOOD_RULES +
      'If you cannot identify the food, reply with ONLY: {"error":"Could not identify food"}';
  }

  static extractJson(text) {
    let t = String(text == null ? '' : text).trim();
    if (!t) return null;

    if (t.startsWith('"') && t.endsWith('"')) {
      try { t = JSON.parse(t); } catch {}
    }

    t = t.replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/i, '');
    t = t.replace(/^"""\s*/, '').replace(/\s*"""$/, '');

    try { return JSON.parse(t); } catch {}

    const s = t.indexOf('{'), e = t.lastIndexOf('}');
    if (s >= 0 && e > s) {
      const candidate = t.slice(s, e + 1);
      try { return JSON.parse(candidate); }
      catch {
        try { return JSON.parse(candidate.replace(/,\s*([}\]])/g, '$1')); }
        catch {}
      }
    }

    if (s >= 0) {
      const repaired = Analyzer.repairTruncated(t.slice(s));
      if (repaired) {
        try { return JSON.parse(repaired); } catch {}
      }
    }

    return null;
  }

  static repairTruncated(text) {
    const arrStart = text.indexOf('[');
    if (arrStart < 0) return null;

    let i = arrStart + 1;
    let depth = 0, inStr = false, esc = false;
    let lastCompleteEnd = -1;

    for (; i < text.length; i++) {
      const c = text[i];
      if (inStr) {
        if (esc) esc = false;
        else if (c === '\\') esc = true;
        else if (c === '"') inStr = false;
        continue;
      }
      if (c === '"') { inStr = true; continue; }
      if (c === '{') { depth++; continue; }
      if (c === '}') {
        depth--;
        if (depth === 0) lastCompleteEnd = i;
      }
    }

    if (lastCompleteEnd < 0) return null;

    const keyMatch = text.slice(0, arrStart).match(/"([^"]+)"\s*:\s*$/);
    const key = keyMatch ? keyMatch[1] : 'items';
    const kept = text.slice(arrStart + 1, lastCompleteEnd + 1).replace(/,\s*$/, '');
    return `{"${key}":[${kept}]}`;
  }

  static errorMessage(err) {
    return err.name === 'AbortError'
      ? 'Request timed out. Please try again.'
      : (err.message || 'Network error. Please check your connection.');
  }

  async request(channel, { formData, jsonBody }) {
    channel.hideError();
    channel.setBusy(true);
    const controller = channel.begin();
    const timer = setTimeout(() => controller.abort(), AppConfig.TIMEOUT_MS);
    try {
      const opts = { method: 'POST', signal: controller.signal };
      if (formData) {
        opts.body = formData;
      } else {
        opts.headers = { 'Content-Type': 'application/json' };
        opts.body = JSON.stringify(jsonBody);
      }
      const res = await fetch(AppConfig.ENDPOINT, opts);
      clearTimeout(timer);
      let data = null;
      try { data = await res.json(); } catch { data = null; }

      console.log('[NutriScan] HTTP', res.status);
      console.log('[NutriScan] reply:', data && data.reply);

      if (!res.ok) {
        throw new Error(this.#httpMessage(res.status, (data && data.error) || ''));
      }
      if (!data || typeof data.reply !== 'string') {
        throw new Error('Unexpected response from the analyzer.');
      }
      return data.reply;
    } finally {
      clearTimeout(timer);
      channel.setBusy(false);
      channel.end();
    }
  }

  #httpMessage(status, rawMsg) {
    if (/philippin|location|access denied|verify/i.test(rawMsg)) {
      return 'This service is available only to visitors inside the Philippines. ' +
        'If you are in the Philippines, turn off any VPN/proxy/private-relay and use a Philippine IP.';
    }
    if (status === 403) return 'Access denied. This service is available only in the Philippines.';
    if (status === 413) return 'Image or text is too large. Try a smaller photo or shorter text.';
    if (status === 415) return 'Unsupported file type. Use JPG, PNG, GIF, or WebP.';
    if (status === 429) return 'Too many requests. Please wait a minute and try again.';
    if (status === 502 || status === 503) return 'Service temporarily unavailable. Please try again shortly.';
    return rawMsg || ('Request failed (' + status + ').');
  }

  async analyzeImage(channel, file) {
    try {
      const form = new FormData();
      form.append('message', Analyzer.imagePrompt());
      form.append('image', file, 'food.jpg');
      channel.setBusy(true, 'Reading every food on the plate…');
      const reply = await this.request(channel, { formData: form });

      const p = Analyzer.extractJson(reply);
      if (p && p.error) {
        channel.showError('The analyzer could not identify food in this photo. Try a clearer, closer picture.');
        return null;
      }
      if (!p) {
        channel.showError('The reply was not readable. Please retry.');
        return null;
      }

      let arr = [];
      if (Array.isArray(p.items)) arr = p.items;
      else if (Array.isArray(p.foods)) arr = p.foods;
      else if (Array.isArray(p.plate)) arr = p.plate;
      else if (Array.isArray(p.detected)) arr = p.detected;
      else if (Array.isArray(p)) arr = p;
      else if (typeof p.name === 'string' || typeof p.food === 'string') arr = [p];

      arr = arr
        .map(i => {
          if (!i || typeof i !== 'object') return null;
          const name = i.name || i.food || i.label;
          if (!name || !String(name).trim()) return null;
          return { ...i, name: String(name).trim() };
        })
        .filter(Boolean);

      console.log('[NutriScan] parsed items:', arr);

      if (!arr.length) {
        channel.showError('No food detected. Try a photo where the plate and dishes are clearly visible.');
        return null;
      }

      return arr.slice(0, 10).map(i => ({
        food: new FoodItem(i),
        grams: clamp(Math.round(i.grams) || 100, 1, 2000)
      }));
    } catch (err) {
      channel.showError(Analyzer.errorMessage(err));
      return null;
    }
  }

  async analyzeName(channel, name) {
    try {
      channel.setBusy(true, 'Analyzing food name…');
      const reply = await this.request(channel, {
        jsonBody: {
          messages: [{ role: 'user', content: Analyzer.textPrompt(name) }],
          max_tokens: 900
        }
      });
      const p = Analyzer.extractJson(reply);
      if (p && p.error) {
        channel.showError('Could not identify that food. Try another search.');
        return null;
      }
      if (!p) {
        channel.showError('The reply was not readable. Please retry.');
        return null;
      }
      const item = Array.isArray(p.items) && p.items[0] ? p.items[0] : p;
      if (typeof item.name === 'string' && item.name.trim()) {
        return new FoodItem(item);
      }
      channel.showError('Could not identify that food. Try another search.');
      return null;
    } catch (err) {
      channel.showError(Analyzer.errorMessage(err));
      return null;
    }
  }
}

